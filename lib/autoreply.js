/**
 * 深鲸 QQ 桥接 —— 自动回复（关键词规则 + 模板 + 防刷）
 *
 * 定位：官方机器人通道收到 c2c / 群（被 @）消息后，**入队之后立刻**按规则回一条，
 * 走被动回复（带原消息 msg_id），不轮询、不等待，做到「秒回」。
 *
 * 设计边界：
 *   · 默认关闭；配置在 ~/.dsh/qq-bridge.json，面板可随时关
 *   · 被动回复窗口 5 分钟（平台限制），本模块在本地 4.5 分钟就不再尝试，避免无谓 40034005
 *   · 防刷：同一会话最小间隔 + 全局每小时上限；连续失败 3 次自动暂停（可手动恢复）
 *   · 规则按数组顺序，命中第一条即用；模式：包含（默认）/ 精确 / 正则
 *   · 模板占位符：{昵称} {内容} {时间}
 *   · 所有自动回复写审计（来源 auto、规则索引、关键词）；普通跳过只计数，
 *     但「回复模板为空」这种配置错误会写一条 结果=跳过 的审计
 *
 * 本模块不 import official.js（避免循环依赖）：真正的「发送」由 official.js 通过
 * 设自动回复发送器() 注入，测试里也可以直接注入假发送器。
 *
 * @module @deepwhale-cn/qq-bridge/autoreply
 */
import { 读配置, 解析路径, 写审计 } from './core.js';

export const 默认回复模板 = '收到～我是深鲸机器人，稍后回复你。';
/** 平台被动回复窗口 5 分钟；本地 4.5 分钟就放弃（留出网络/排队余量） */
export const 回复窗口毫秒 = 4.5 * 60 * 1000;
export const 失败暂停阈值 = 3;
const 小时毫秒 = 3600 * 1000;
const 会话记忆上限 = 2000;

/* ────────────────────────── 规则与模板 ────────────────────────── */

export const 匹配模式表 = ['包含', '精确', '正则'];

/** 匹配规则：按数组顺序，命中第一条即返回。正则写错就当这条不命中（不让一条坏规则拖垮全部） */
export function 匹配规则(规则表 = [], 文本 = '') {
  const 内容 = String(文本 == null ? '' : 文本);
  const 表 = Array.isArray(规则表) ? 规则表 : [];
  for (let 序 = 0; 序 < 表.length; 序 += 1) {
    const 规则 = 表[序] && typeof 表[序] === 'object' ? 表[序] : {};
    const 词表 = Array.isArray(规则.关键词) ? 规则.关键词 : [];
    const 模式 = 匹配模式表.includes(规则.模式) ? 规则.模式 : '包含';
    for (const 原词 of 词表) {
      const 关键词 = String(原词 == null ? '' : 原词).trim();
      if (关键词 === '') continue;
      let 命中 = false;
      if (模式 === '精确') {
        命中 = 内容.trim() === 关键词;
      } else if (模式 === '正则') {
        try { 命中 = new RegExp(关键词, 'i').test(内容); } catch { 命中 = false; }
      } else {
        命中 = 内容.toLowerCase().includes(关键词.toLowerCase());
      }
      if (命中) return { 命中: true, 索引: 序, 关键词, 模式, 回复: String(规则.回复 == null ? '' : 规则.回复) };
    }
  }
  return { 命中: false, 索引: -1, 关键词: '', 模式: '', 回复: '' };
}

function 时间文本(毫秒) {
  const d = new Date(毫秒);
  const 补 = (n) => String(n).padStart(2, '0');
  return 补(d.getHours()) + ':' + 补(d.getMinutes());
}

/** 模板占位符替换；未知占位符原样保留（用户写错能看出来） */
export function 渲染模板(模板, 变量 = {}) {
  const 昵称 = String(变量.昵称 == null ? '' : 变量.昵称).trim() || '你';
  const 内容 = String(变量.内容 == null ? '' : 变量.内容);
  const 时间 = 变量.时间 !== undefined ? String(变量.时间) : 时间文本(变量.现在 === undefined ? Date.now() : 变量.现在);
  return String(模板 == null ? '' : 模板)
    .split('{昵称}').join(昵称)
    .split('{内容}').join(内容)
    .split('{时间}').join(时间);
}

/** 事件时间戳（官方 d.timestamp 是带时区的 ISO 串）；解析不出来返回 null（按新消息处理） */
export function 消息时刻毫秒(数据 = {}) {
  const 原 = 数据 && (数据.timestamp || 数据.时间);
  if (!原) return null;
  const 毫秒 = Date.parse(String(原));
  return Number.isFinite(毫秒) ? 毫秒 : null;
}

/* ────────────────────────── 运行状态 ────────────────────────── */

function 日期键(现在) {
  const d = new Date(现在);
  const 补 = (n) => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + 补(d.getMonth() + 1) + '-' + 补(d.getDate());
}

export function 造自动回复状态() {
  return {
    会话末次: new Map(),
    进行中: new Set(),      // 已经决定要回、但还没发完的会话（防同时到达两条消息各回一条）
    小时窗口: [],
    今日: { 日期: 日期键(Date.now()), 次数: 0 },
    连续失败: 0,
    暂停: false,
    暂停原因: '',
    暂停时刻: null,
    上次回复: null,
    上次规则: null,
    总计: 0,
    跳过: {},
  };
}

/** 生产用进程内单例（测试用 造自动回复状态 + 选项.状态 注入，互不影响） */
let 单例 = 造自动回复状态();

export function 重置自动回复状态() { 单例 = 造自动回复状态(); return 单例; }
export function 取自动回复状态() { return 单例; }
export function 设自动回复状态(状态) { 单例 = 状态 || 造自动回复状态(); return 单例; }

function 清理窗口(状态, 现在) {
  状态.小时窗口 = (状态.小时窗口 || []).filter((t) => Number.isFinite(t) && 现在 - t < 小时毫秒);
  状态.小时窗口 = 状态.小时窗口.slice(-10000);
}

function 滚动今日(状态, 现在) {
  const 键 = 日期键(现在);
  if (!状态.今日 || 状态.今日.日期 !== 键) 状态.今日 = { 日期: 键, 次数: 0 };
}

function 记跳过(状态, 原因) {
  const 类 = 跳过类别(原因);
  状态.跳过[类] = (状态.跳过[类] || 0) + 1;
}

function 跳过类别(原因) {
  const 串 = String(原因 || '');
  for (const 前缀 of [
    '自动回复未开启', '范围只允许私聊', '已暂停', '入站没有可读文本', 'msg_id 已超过',
    '同一会话最小间隔', '同一会话正在回复中', '全局每小时上限', '回复模板为空', '发送器未装配',
    '会话类型不在', '缺少 msg_id',
  ]) {
    if (串.startsWith(前缀)) return 前缀;
  }
  return '其他';
}

function 会话键(记录) {
  return 记录.会话类型 === 'group'
    ? 'group:' + String(记录.group_openid || '')
    : 'c2c:' + String(记录.openid || '');
}

function 记会话(状态, 键, 现在) {
  状态.会话末次.set(键, 现在);
  if (状态.会话末次.size > 会话记忆上限) {
    const 最旧 = 状态.会话末次.keys().next();
    if (!最旧.done) 状态.会话末次.delete(最旧.value);
  }
}

function 数值(值, 缺省) {
  const n = Number(值);
  return Number.isFinite(n) && n >= 0 ? n : 缺省;
}

function 尾号(值) {
  const 串 = String(值 == null ? '' : 值);
  return 串 === '' ? '' : (串.length <= 6 ? 串 : '…' + 串.slice(-6));
}

/* ────────────────────────── 评估（纯判断，不发请求） ────────────────────────── */

/**
 * 判断这条入站要不要自动回复。
 * @returns {{动作:'回复'|'跳过', 原因?:string, 正文?:string, 命中?:object, 键?:string}}
 */
export function 评估自动回复({ 记录 = {}, 数据 = {}, 配置 = {}, 状态 = 单例, 现在 = Date.now() } = {}) {
  if (!配置.official_auto_reply) return { 动作: '跳过', 原因: '自动回复未开启' };
  const 类型 = 记录.会话类型;
  if (类型 !== 'c2c' && 类型 !== 'group') return { 动作: '跳过', 原因: '会话类型不在自动回复范围（只支持私聊/群）' };
  if (配置.official_reply_scope !== 'all' && 类型 !== 'c2c') return { 动作: '跳过', 原因: '范围只允许私聊（群消息不自动回）' };
  if (状态.暂停) return { 动作: '跳过', 原因: '已暂停：' + (状态.暂停原因 || '连续失败') };

  const 文本 = String(记录.文本 == null ? '' : 记录.文本).trim();
  if (文本 === '') return { 动作: '跳过', 原因: '入站没有可读文本（图片/表情/非文字）' };
  if (String(记录.msg_id || '').trim() === '') {
    return { 动作: '跳过', 原因: '缺少 msg_id（没有被动回复凭证，发出去会 40034105）' };
  }

  const 消息时刻 = 消息时刻毫秒(数据);
  if (消息时刻 !== null && 现在 - 消息时刻 > 回复窗口毫秒) {
    return { 动作: '跳过', 原因: 'msg_id 已超过 4.5 分钟（被动回复窗口已过，发了也会 40034005）' };
  }

  const 键 = 会话键(记录);
  // 两条消息几乎同时到达：第一条还在发，第二条必须让路（否则会同一会话各回一条）
  if (状态.进行中 && 状态.进行中.has(键)) {
    return { 动作: '跳过', 原因: '同一会话正在回复中（上一条还没发完）' };
  }
  const 间隔 = 数值(配置.official_reply_min_interval_ms, 30000);
  const 末次 = 状态.会话末次.get(键) || 0;
  if (间隔 > 0 && 末次 > 0 && 现在 - 末次 < 间隔) {
    return { 动作: '跳过', 原因: '同一会话最小间隔未到（还剩 ' + Math.ceil((间隔 - (现在 - 末次)) / 1000) + 's）' };
  }

  清理窗口(状态, 现在);
  const 上限 = 数值(配置.official_reply_hourly_cap, 60);
  const 在途 = 状态.进行中 ? 状态.进行中.size : 0;
  if (上限 > 0 && 状态.小时窗口.length + 在途 >= 上限) {
    return { 动作: '跳过', 原因: '全局每小时上限已到（' + 上限 + ' 条/小时）' };
  }

  const 命中 = 匹配规则(配置.official_reply_rules, 文本);
  // 显式设成空串 = 用户清空了模板 → 跳过（不能用 || 回落默认，否则「清空」永远无效）
  const 默认模板 = 配置.official_reply_text === undefined || 配置.official_reply_text === null
    ? 默认回复模板
    : 配置.official_reply_text;
  const 模板 = 命中.命中 ? 命中.回复 : 默认模板;
  let 正文 = 渲染模板(模板, { 昵称: 记录.昵称, 内容: 文本, 现在 }).trim();
  if (正文 === '') return { 动作: '跳过', 原因: '回复模板为空（规则或默认模板没写内容）', 命中 };
  if (正文.length > 4000) 正文 = 正文.slice(0, 4000);
  return { 动作: '回复', 正文, 命中, 键 };
}

/* ────────────────────────── 执行 ────────────────────────── */

let 发送实现 = null;

/** official.js 在模块加载时注入 发送官方消息；测试可直接注入假发送器 */
export function 设自动回复发送器(fn) {
  发送实现 = typeof fn === 'function' ? fn : null;
}

export function 取自动回复发送器() { return 发送实现; }

/**
 * 处理一条入站：评估 → （需要时）立即被动回复 → 更新防刷状态 + 审计。
 * 永不抛错（自动回复出错不能影响收消息/连接）。
 */
export async function 触发自动回复(记录 = {}, 数据 = {}, 选项 = {}) {
  const 路径 = 选项.路径 || 解析路径();
  const 现在 = typeof 选项.现在 === 'function'
    ? 选项.现在()
    : (Number.isFinite(选项.现在) ? 选项.现在 : Date.now());
  const 状态 = 选项.状态 || 单例;
  const 配置 = 选项.配置 || 读配置(路径);

  const 评估 = 评估自动回复({ 记录, 数据, 配置, 状态, 现在 });
  if (评估.动作 !== '回复') {
    记跳过(状态, 评估.原因);
    // 「空回复」这类配置错误要留痕（其余跳过只计数，避免每条入站都多一行审计）
    if (/回复模板为空/.test(String(评估.原因))) {
      写审计({
        动作: '自动回复', 结果: '跳过', 来源: 'auto', 通道: 'official',
        会话类型: 记录.会话类型, 错误: 评估.原因,
        规则: 评估.命中 && 评估.命中.命中 ? ('#' + 评估.命中.索引) : '默认模板',
        规则索引: 评估.命中 && 评估.命中.命中 ? 评估.命中.索引 : null,
        关键词: 评估.命中 && 评估.命中.命中 ? 评估.命中.关键词 : '',
      }, 路径);
    }
    return { 动作: '跳过', 原因: 评估.原因, 命中: 评估.命中 };
  }

  const 发送 = 选项.发送 || 发送实现;
  if (typeof 发送 !== 'function') {
    记跳过(状态, '发送器未装配');
    return { 动作: '跳过', 原因: '发送器未装配', 命中: 评估.命中 };
  }

  const 命中 = 评估.命中 || { 命中: false, 索引: -1 };
  const 目标参数 = 记录.会话类型 === 'group'
    ? { channel: 'group', group_openid: String(记录.group_openid || '') }
    : { channel: 'c2c', openid: String(记录.openid || '') };
  const 审计基础 = {
    动作: '自动回复', 来源: 'auto', 通道: 'official', 会话类型: 记录.会话类型,
    目标: 尾号(记录.会话类型 === 'group' ? 记录.group_openid : 记录.openid),
    规则: 命中.命中 ? ('#' + 命中.索引) : '默认模板',
    规则索引: 命中.命中 ? 命中.索引 : null,
    关键词: 命中.命中 ? 命中.关键词 : '',
    匹配模式: 命中.命中 ? 命中.模式 : '',
    被动回复: 记录.msg_id ? 'msg_id' : '无',
    内容: 评估.正文.slice(0, 200),
  };

  const 键 = 评估.键 || 会话键(记录);
  if (!状态.进行中) 状态.进行中 = new Set();
  状态.进行中.add(键);
  let 结果 = null;
  try {
    结果 = await 发送({ ...目标参数, text: 评估.正文, msg_id: String(记录.msg_id || '') }, {
      ...选项,
      配置,
      路径,
      来源: 'auto',
    });
  } catch (e) {
    结果 = { ok: false, 原因: '发送抛错：' + String((e && e.message) || e) };
  } finally {
    状态.进行中.delete(键);
  }

  if (结果 && 结果.ok) {
    清理窗口(状态, 现在);
    状态.小时窗口.push(现在);
    滚动今日(状态, 现在);
    状态.今日.次数 += 1;
    状态.总计 += 1;
    状态.连续失败 = 0;
    状态.上次回复 = 现在;
    状态.上次规则 = 命中.命中 ? { 索引: 命中.索引, 关键词: 命中.关键词, 模式: 命中.模式 } : null;
    记会话(状态, 键, 现在);
    写审计({ ...审计基础, 结果: '成功', 消息号: 结果.消息号 === undefined ? null : 结果.消息号 }, 路径);
    return { 动作: '回复', 成功: true, 正文: 评估.正文, 命中, 消息号: 结果.消息号 };
  }

  const 原因 = String((结果 && 结果.原因) || '发送失败');
  状态.连续失败 += 1;
  状态.暂停时刻 = 现在;
  记会话(状态, 键, 现在); // 失败也计入间隔，避免狂重试
  if (状态.连续失败 >= 失败暂停阈值) {
    状态.暂停 = true;
    状态.暂停原因 = '连续 ' + 状态.连续失败 + ' 次自动回复失败：' + 原因;
  }
  写审计({
    ...审计基础, 结果: '失败', 错误: 原因,
    code: 结果 && 结果.code, trace_id: 结果 && 结果.trace_id,
    连续失败: 状态.连续失败, 已暂停: 状态.暂停,
  }, 路径);
  return {
    动作: '回复', 成功: false, 原因, 命中,
    连续失败: 状态.连续失败, 已暂停: 状态.暂停,
  };
}

/** 手动恢复（面板/HTTP 调用）：清暂停与连续失败计数 */
export function 恢复自动回复(选项 = {}) {
  const 路径 = 选项.路径 || 解析路径();
  const 状态 = 选项.状态 || 单例;
  状态.暂停 = false;
  状态.连续失败 = 0;
  状态.暂停原因 = '';
  状态.暂停时刻 = null;
  写审计({ 动作: '自动回复', 结果: '恢复', 来源: 'auto', 说明: '手动恢复自动回复' }, 路径);
  return 自动回复统计(选项.配置 || 读配置(路径), 选项.现在 === undefined ? Date.now() : 选项.现在);
}

/** 面板/HTTP 用的当前统计（不写审计） */
export function 自动回复统计(配置 = {}, 现在 = Date.now()) {
  清理窗口(单例, 现在);
  滚动今日(单例, 现在);
  return {
    运行状态: 单例.暂停 ? '已暂停' : '运行中',
    今日次数: 单例.今日.次数,
    今日日期: 单例.今日.日期,
    小时次数: 单例.小时窗口.length,
    每小时上限: 数值(配置 && 配置.official_reply_hourly_cap, 60),
    连续失败: 单例.连续失败,
    暂停: 单例.暂停,
    暂停原因: 单例.暂停原因,
    暂停时刻: 单例.暂停时刻 ? new Date(单例.暂停时刻).toISOString() : null,
    上次回复: 单例.上次回复 ? new Date(单例.上次回复).toISOString() : null,
    上次规则: 单例.上次规则,
    总计: 单例.总计,
    跳过: { ...单例.跳过 },
    窗口毫秒: 回复窗口毫秒,
  };
}
